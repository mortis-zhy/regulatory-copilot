"""争议条目裁定书 — 回原文核实的结论。

每条给出：评审指控 / 原文证据 / 裁定。
"""
import re
from pathlib import Path
import fitz

ROOT = Path(__file__).resolve().parent
SRC = {
    "A": ROOT / "2026-08-26_GB 4785草案V4.3.5_1315_不带Comments的版本.pdf",
    "B": ROOT / "GB 4785-2019 《汽车及挂车外部照明和光信号装置的安装规定》.pdf",
}
DOCS = {k: fitz.open(v) for k, v in SRC.items()}


def grab(ver, pattern, page_hint=None):
    """返回命中的 (页, 文本)。"""
    rx = re.compile(pattern)
    for i, p in enumerate(DOCS[ver]):
        if page_hint and i + 1 != page_hint:
            continue
        t = p.get_text()
        m = rx.search(t)
        if m:
            return i + 1, t[max(0, m.start() - 120): m.end() + 200].replace("\n", " ")
    return None, None


FINDINGS = []


def record(no, claim, evidence, ruling):
    FINDINGS.append((no, claim, evidence, ruling))


# ── 1. 弯道照明曲率半径 ──────────────────────────────────────────────
_, a = grab("A", r"曲率半径不大于500m", 28)
_, b = grab("B", r"曲率半径应不大于500m", 26)
record(
    1,
    "评审：报告把 500m 误写为 500mm，构成单位错误假差异",
    f"A p28「…水平曲率半径不大于500m」/ B p26「…水平曲率半径应不大于500m」",
    "**评审对、报告错**。两版原文都是 m，报告 A 栏摘录误写为 mm。"
    "报告 §11.8 已自行标注「单位展示差异——已核验原文两版均为 m」，但正文表格未修正。",
)

# ── 2. 示廓灯横向 500mm 放宽 ────────────────────────────────────────
_, a = grab("A", r"此距离可以放宽至500mm", 50)
_, b_400 = grab("B", r"不大于400mm", 39)
record(
    2,
    "评审：该放宽条款 B 版同样存在，报告标为「A 独有」属核验错误",
    f"A p50「…应不大于400mm。若为满足5.13.4.2要求，此距离可以放宽至500mm」/ "
    f"B p39 示廓灯横向仅见「…不大于400mm」，未检索到 500mm 放宽表述",
    "**报告对、评审错**。B 版确有 400mm 基线，但无「放宽至 500mm」条款；"
    "该放宽为 A 草案新增。评审的检索可能落在不同条款（侧回复反射器 3m→4m）。",
)

# ── 3. 侧标志灯间距 6m→4m ───────────────────────────────────────────
_, a = grab("A", r"长度小于6\s*m的M1类和N1车辆，琥珀色的侧标志灯", 40)
_, b = grab("B", r"长度大于6m\s*的车辆应配备", 46)
record(
    3,
    "评审：报告称「≤6m 改 ≤4m」是误读，实为车长豁免条款",
    f"A p40「…长度小于6 m的M1类和N1车辆，琥珀色的侧标志灯应以与同侧转向信号灯同频率同相闪烁」/ "
    f"B p46「5.18.1 配备 除了带驾驶室底盘外,长度大于6m 的车辆应配备」",
    "**评审对、报告错**。两版都是「长度 6m」的分界，且都用于侧标志灯配备/闪烁条件，"
    "与侧回复反射器的 3m→4m 是不同条款。报告若写成「6m 改 4m」确为串条款。",
)

# ── 4. 醒目标志光色 ─────────────────────────────────────────────────
_, a = grab("A", r"车身反光标识[：:]\s*红色、白色和橙色", 19)
_, b = grab("B", r"车身反光标识[：:]\s*红色和白色", 19)
record(
    4,
    "评审：光色差异来自引用标准更新，非 GB4785 自身光色规定，归因错误",
    f"A p19 表5「醒目标志 车身反光标识：红色、白色和橙色 车辆尾部标志板：红色和黄色」/ "
    f"B p19 表5「醒目标志 车身反光标识:红色和白色 尾部标志板:红色和黄色」",
    "**报告对、评审错**。两版均在**表5 光色**中直接规定醒目标志颜色，"
    "A 新增「橙色」是 GB4785 表5 本身的变更。B 的规范性引用含 GB23254/GB25990，"
    "但那是灯具性能标准，颜色规定由 GB4785 表5 直接承载。",
)

# ── 输出 ────────────────────────────────────────────────────────────
print("=" * 80)
print("争议条目裁定书 — 基于三份源 PDF 原文的逐条核实")
print("=" * 80)
for no, claim, ev, ruling in FINDINGS:
    print(f"\n【争议 {no}】")
    print(f"  评审指控：{claim}")
    print(f"  原文证据：{ev}")
    print(f"  裁定    ：{ruling}")

for d in DOCS.values():
    d.close()
