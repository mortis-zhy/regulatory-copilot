/**
 * `consistency.ts` 的自测 —— 用**合成表格**喂它。
 *
 * 为什么必须用合成用例：报告自己的「一致性自查」页曾经报出
 * 「⛔ 2 项严重 · ⚠ 55 项中等」，其中 **53 项是检查器自己的误报**
 * （它把表的第 2 格一律当「主题列」：
 *   - 「| 参数 | 单位 | A | B | C |」的第 2 格是**单位**，
 *     两行都是 `s` 就被判成「s 重复 3 次」；
 *   - 「| 版本 | 原文取值 | 条款 | … |」里 B、C 两版都写
 *     「—该版无此规定（已核）」，是**两行合法的对照**，被判成「重复行」）。
 * 这类误报只有拿**已知答案**的合成表格去撞才抓得住 ——
 * 对着真报告看是看不出「它本来就不该报」的。
 *
 * 顺带守住两条「不能瞎报」的判据：
 *   - 430000cd（同时点亮远光灯最大发光强度之和）是**真实光度值**，
 *     页码不可能有 5 位 —— 不能报「疑似页码串位」；
 *   - 「视表面/透光面/发光面」在 GB 4785 里是**三个不同的面**
 *     （A 3.1.8/3.1.9/3.1.10），不能报「同义术语混用」。
 */
import assert from "node:assert/strict";
import { checkConsistency } from "./dist/consistency.js";

let checks = 0;
const ok = (cond, msg) => {
  assert.ok(cond, msg);
  checks++;
};
const kinds = (md) => checkConsistency(md).issues.filter((i) => i.kind);

/* --- 1. 真的重复行要抓得到 ------------------------------------------------ */
{
  const md = `
| 序号 | 主题 | 参数 | A 草案 | B 现行 | 判定 |
|---|---|---|---|---|---|
| 01 | 近光灯 | 最大离地高度 | 1200mm | 1200mm | 一致 |
| 02 | 近光灯 | 最大离地高度 | 1200mm | 1200mm | 一致 |
| 03 | 转向信号灯 | 闪光频率 | 90次/min | 90次/min | 一致 |
`;
  const dup = kinds(md).filter((i) => i.kind === "duplicate");
  ok(dup.length === 1, `真重复行必须报出来，实际报了 ${dup.length} 条`);
  ok(dup[0].detail.includes("近光灯"), "重复行要指名是哪一行");
}

/* --- 2. 版本对照表里的「两版都无此规定」不是重复行 ------------------------ */
{
  const md = `
| 版本 | 原文取值 | 条款 | 页码 |
|---|---|---|---|
| **A 草案** | 5.2.4.1 横向：离地高度不小于500mm | 5.2.4.1 | 第26页 |
| **B 现行** | 5.2.4.1 横向：离地高度不小于500mm | 5.2.4.1 | 第24页 |
| **C UN R48-09** | — 该版无此规定（已核） | — | — |
`;
  const dup = kinds(md).filter((i) => i.kind === "duplicate");
  ok(dup.length === 0, `版本对照表里不该报重复行，实际报了 ${dup.length} 条：${dup.map((d) => d.detail)}`);
}

/* --- 3. 第 2 格是「单位」的表，两行同单位不是重复行 ------------------------ */
{
  const md = `
| 参数 | 单位 | A 草案 | B 现行 | C UN R48-09 | 判定 |
|---|---|---|---|---|---|
| 追尾警告信号作用时间上限 | s | 3 | 3 | 3 | A/B 一致 |
| 追尾警告信号 TTC（碰撞时间）上限 | s | 1.4 | 1.4 | 1.4 | A/B 一致 |
`;
  const dup = kinds(md).filter((i) => i.kind === "duplicate");
  ok(dup.length === 0, `单位列不该被当主题列，实际报了 ${dup.length} 条：${dup.map((d) => d.detail)}`);
}

/* --- 4. 5 位以上的数字不是页码串位（除非这张表真有「页码」列） -------------- */
{
  const md = `
| 参数 | 单位 | A 草案 | B 现行 | C UN R48-09 | 判定 |
|---|---|---|---|---|---|
| 同时点亮远光灯最大发光强度之和 | cd | 430000 | 430000 | — | **C 未定位到** |
`;
  const stray = kinds(md).filter((i) => i.label.includes("页码串位"));
  ok(stray.length === 0, `430000cd 是真实光度值，不该报页码串位，实际报了 ${stray.length} 条`);
}
{
  // 「疑似页码串位」这条检查**已删除**：页码是「第26页」，裸 5 位以上数字
  // 从来不是页码；而 430000cd 这种真实光度值恰恰是 6 位。
  // 只会误报的检查比没有检查更糟 —— 读者会学会忽略整块自查面板。
  const md = `
| 参数 | 条款 | 页码 | 取值 |
|---|---|---|---|
| 近光灯 | 5.2.4.2 | 第26页 | 1200mm |
`;
  const stray = kinds(md).filter((i) => i.label.includes("页码串位"));
  ok(stray.length === 0, `不该再报页码串位，实际报了 ${stray.length} 条`);
}

/* --- 5. 「视表面/透光面/发光面」不是同义词，不能报术语混用 ------------------ */
{
  const md = `
| 版本 | 原文取值 | 条款 | 页码 |
|---|---|---|---|
| **A 草案** | 视表面应不小于500mm | 5.2.4.1 | 第26页 |
| **B 现行** | 透光面应不小于500mm | 5.2.4.1 | 第24页 |
| **C UN R48-09** | 发光面 should not be less than 500 mm | 6.2.4.1 | 第40页 |
`;
  const term = kinds(md).filter((i) => i.kind === "term");
  ok(term.length === 0, `三个不同的面不是术语混用，实际报了 ${term.length} 条`);
}

/* --- 6. 单位互换（真问题）仍然要报 ---------------------------------------- */
{
  const md = `
| 参数 | A 草案 | B 现行 |
|---|---|---|
| 弯道照明曲率半径 | 不大于500mm | 不大于500m |
`;
  const unit = kinds(md).filter((i) => i.kind === "unit");
  ok(unit.length >= 1, `m / mm 互换必须报出来，实际报了 ${unit.length} 条`);
}

/* --- 7. 截断摘录：只算**以「…」收尾**的，原文自带的省略号不算 -------------- */
{
  // 原文自带的省略号（GB 4785 A 的 4.x 正文里就有这种）
  const src = `
| 版本 | 原文取值 | 条款 | 页码 |
|---|---|---|---|
| **A 草案** | 安装时其基准轴线应平行于停放面……各灯具每个方向上允差为±3° | 4.5 | 第18页 |
`;
  const t1 = kinds(src).filter((i) => i.label.includes("截断"));
  ok(t1.length === 0, `原文自带的省略号不是截断，实际报了 ${t1.length} 条`);
}
{
  // 我们自己截断的（clipExcerpt 收尾是「 …」）
  const cut = `
| 版本 | 原文取值 | 条款 | 页码 |
|---|---|---|---|
| **A 草案** | 安装时其基准轴线应平行于车辆在道路上的停放面，各灯具每个方向上允差为 ±3° | 4.5 | 第18页 |
`;
  // 造 13 行触发阈值 >12
  const many = cut + Array.from({ length: 13 }, (_, i) =>
    `| **A 草案** | 这是一段被截断的原文摘录，第 ${i} 行，后面还有很多字没有显示出来 … | 4.5 | 第18页 |`).join("\n");
  const t2 = kinds(many).filter((i) => i.label.includes("截断"));
  ok(t2.length === 1, `真截断必须报出来，实际报了 ${t2.length} 条`);
}

console.log(`_test_consistency.mjs — ${checks} checks passed`);
